/// Verdict classification for a completed ISP data plan audit.
enum AuditVerdict {
  conforme('CONFORME', 'Forfait fidèle aux mégas promis'),
  suspect('SUSPECT', 'Écart modéré ou arrondi par session détecté'),
  anomalieCritique(
    'ANOMALIE_CRITIQUE',
    'Épuisement anormal avant livraison du volume promis',
  );

  const AuditVerdict(this.code, this.subtitle);

  final String code;
  final String subtitle;

  static AuditVerdict fromScore(double scorePct) {
    if (scorePct >= 92.0) return AuditVerdict.conforme;
    if (scorePct >= 78.0) return AuditVerdict.suspect;
    return AuditVerdict.anomalieCritique;
  }
}

/// Diagnostic report generated by Gemma 4 (or deterministic fallback analyzer).
class GemmaAuditReport {
  const GemmaAuditReport({
    required this.verdict,
    required this.veracityScorePct,
    required this.missingMb,
    required this.realCostPerGbXaf,
    required this.technicalExplanation,
    required this.cameroonSummary,
    required this.modelUsed,
    required this.generatedAt,
  });

  final AuditVerdict verdict;
  final double veracityScorePct;
  final double missingMb;
  final double realCostPerGbXaf;
  final String technicalExplanation;
  final String cameroonSummary;
  final String modelUsed;
  final DateTime generatedAt;
}
